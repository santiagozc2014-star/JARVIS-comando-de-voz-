package com.jarvis.wakeword.memory

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.AtomicFile
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.io.DataInputStream
import java.io.DataOutputStream
import java.io.File
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * App-private encrypted memory storage.
 *
 * AES-256-GCM provides confidentiality and integrity. The encryption key is
 * generated by Android Keystore and is never stored in the app's files.
 */
class EncryptedMemoryStore(context: Context) : MemoryStore {
    private val atomicFile = AtomicFile(
        File(context.applicationContext.filesDir, FILE_NAME)
    )

    override suspend fun readAll(): List<MemoryEntry> = withContext(Dispatchers.IO) {
        if (!atomicFile.baseFile.exists()) return@withContext emptyList()
        if (atomicFile.baseFile.length() > MAX_FILE_BYTES) {
            throw IllegalStateException("El archivo de memoria supera el tamaño permitido.")
        }
        val encrypted = atomicFile.openRead().use { it.readBytes() }
        decrypt(encrypted)
    }

    override suspend fun writeAll(entries: List<MemoryEntry>) = withContext(Dispatchers.IO) {
        val payload = serialize(entries)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey())
        val encrypted = cipher.iv + cipher.doFinal(payload)
        require(encrypted.size <= MAX_FILE_BYTES) {
            "La memoria ocupa más espacio del permitido."
        }

        val output = atomicFile.startWrite()
        try {
            output.write(encrypted)
            atomicFile.finishWrite(output)
        } catch (error: Exception) {
            atomicFile.failWrite(output)
            throw error
        }
    }

    override suspend fun clear() = withContext(Dispatchers.IO) {
        atomicFile.delete()
    }

    private fun decrypt(encrypted: ByteArray): List<MemoryEntry> {
        if (encrypted.size < IV_BYTES + TAG_BYTES) {
            throw IllegalStateException("El archivo de memoria está incompleto.")
        }
        val iv = encrypted.copyOfRange(0, IV_BYTES)
        val ciphertext = encrypted.copyOfRange(IV_BYTES, encrypted.size)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, getOrCreateKey(), GCMParameterSpec(TAG_BITS, iv))
        return deserialize(cipher.doFinal(ciphertext))
    }

    private fun getOrCreateKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        val existing = keyStore.getKey(KEY_ALIAS, null)
        if (existing is SecretKey) return existing

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build()
        )
        return generator.generateKey()
    }

    private fun serialize(entries: List<MemoryEntry>): ByteArray {
        require(entries.size <= MAX_ENTRIES) { "Hay demasiados recuerdos guardados." }
        val buffer = ByteArrayOutputStream()
        DataOutputStream(buffer).use { output ->
            output.writeInt(FORMAT_MAGIC)
            output.writeInt(FORMAT_VERSION)
            output.writeInt(entries.size)
            entries.forEach { entry ->
                output.writeBoundedString(entry.id, MAX_ID_BYTES)
                output.writeBoundedString(entry.title, MAX_TITLE_BYTES)
                output.writeBoundedString(entry.content, MAX_CONTENT_BYTES)
                require(entry.tags.size <= MAX_TAGS) { "Un recuerdo contiene demasiadas etiquetas." }
                output.writeInt(entry.tags.size)
                entry.tags.forEach { output.writeBoundedString(it, MAX_TAG_BYTES) }
                output.writeLong(entry.createdAtMillis)
                output.writeLong(entry.updatedAtMillis)
            }
        }
        return buffer.toByteArray().also {
            require(it.size + IV_BYTES + TAG_BYTES <= MAX_FILE_BYTES) {
                "La memoria ocupa más espacio del permitido."
            }
        }
    }

    private fun deserialize(payload: ByteArray): List<MemoryEntry> {
        DataInputStream(ByteArrayInputStream(payload)).use { input ->
            if (input.readInt() != FORMAT_MAGIC || input.readInt() != FORMAT_VERSION) {
                throw IllegalStateException("La versión del archivo de memoria no es compatible.")
            }
            val count = input.readInt()
            if (count !in 0..MAX_ENTRIES) {
                throw IllegalStateException("El archivo contiene un número de recuerdos no válido.")
            }
            val entries = ArrayList<MemoryEntry>(count)
            val ids = HashSet<String>()
            repeat(count) {
                val id = input.readBoundedString(MAX_ID_BYTES)
                val title = input.readBoundedString(MAX_TITLE_BYTES)
                val content = input.readBoundedString(MAX_CONTENT_BYTES)
                val tagCount = input.readInt()
                if (tagCount !in 0..MAX_TAGS) {
                    throw IllegalStateException("Un recuerdo contiene etiquetas no válidas.")
                }
                val tags = List(tagCount) { input.readBoundedString(MAX_TAG_BYTES) }
                val createdAt = input.readLong()
                val updatedAt = input.readLong()
                if (id.isBlank() || title.isBlank() || content.isBlank() || !ids.add(id)) {
                    throw IllegalStateException("El archivo contiene un recuerdo no válido.")
                }
                entries += MemoryEntry(id, title, content, tags, createdAt, updatedAt)
            }
            if (input.available() != 0) {
                throw IllegalStateException("El archivo contiene datos adicionales no válidos.")
            }
            return entries
        }
    }

    private fun DataOutputStream.writeBoundedString(value: String, maxBytes: Int) {
        val bytes = value.toByteArray(Charsets.UTF_8)
        require(bytes.size in 1..maxBytes) { "Un campo de memoria está vacío o supera el límite." }
        writeInt(bytes.size)
        write(bytes)
    }

    private fun DataInputStream.readBoundedString(maxBytes: Int): String {
        val length = readInt()
        if (length !in 1..maxBytes) {
            throw IllegalStateException("El archivo contiene un campo de memoria no válido.")
        }
        val bytes = ByteArray(length)
        readFully(bytes)
        return String(bytes, Charsets.UTF_8)
    }

    private companion object {
        const val FILE_NAME = "jarvis_structured_memory.enc"
        const val KEY_ALIAS = "com.jarvis.wakeword.structured_memory"
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_BYTES = 12
        const val TAG_BITS = 128
        const val TAG_BYTES = TAG_BITS / 8
        const val MAX_ENTRIES = 300
        const val MAX_ID_BYTES = 128
        const val MAX_TITLE_BYTES = 4 * 1024
        const val MAX_CONTENT_BYTES = 16 * 1024
        const val MAX_TAG_BYTES = 256
        const val MAX_TAGS = 20
        const val MAX_FILE_BYTES = 2 * 1024 * 1024
        const val FORMAT_MAGIC = 0x4A4D454D
        const val FORMAT_VERSION = 1
    }
}
